"""
Deterministic CSS extractor.

Walks every captured page's inline <style> blocks and every downloaded
.css asset, concatenates, strips Angular-specific noise, then writes:

  real-project/assets/css/tokens.css     — generated from design-tokens.json
  real-project/assets/css/reset.css      — fixed modern reset (templates/)
  real-project/assets/css/raw.css        — concatenated + Angular-stripped
  real-project/assets/css/base.css       — placeholder; the AI-powered
                                           consolidate-css step fills this in

The AI consolidator (called from orchestrator.py) takes raw.css + tokens
as input and produces the final base.css. Splitting deterministic
extraction from AI cleanup means the deterministic stage is testable.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from bs4 import BeautifulSoup


# Angular / Webpack / Material noise
NOISE_SELECTOR_PREFIXES = (
    "_nghost-", "_ngcontent-", "ng-tns-", "[_nghost", "[_ngcontent",
)
NOISE_AT_RULES = (
    "@charset",
)

ANGULAR_ATTR_SELECTOR_RE = re.compile(
    r"\[_ng(?:host|content|tns)-[^\]]+\]", re.I
)
ANGULAR_TAG_RE = re.compile(r"\b(?:app|mat|cdk|ng|md)-[a-z][\w-]*", re.I)


@dataclass
class CssExtractStats:
    files_read: int = 0
    inline_blocks_read: int = 0
    bytes_raw_total: int = 0
    bytes_clean_total: int = 0
    rules_dropped_angular: int = 0


def _gather_from_pages(pages_dir: Path) -> tuple[str, int]:
    parts: list[str] = []
    inline_count = 0
    for page_dir in pages_dir.iterdir() if pages_dir.exists() else []:
        rendered = page_dir / "rendered.html"
        if not rendered.exists():
            continue
        html = rendered.read_text(encoding="utf-8", errors="ignore")
        soup = BeautifulSoup(html, "lxml")
        for s in soup.find_all("style"):
            text = s.text or ""
            if text.strip():
                parts.append(f"/* === inline from {page_dir.name} === */\n{text}\n")
                inline_count += 1
    return "\n".join(parts), inline_count


def _gather_from_assets(assets_root: Path) -> tuple[str, int]:
    stylesheets = assets_root / "stylesheets"
    parts: list[str] = []
    files = 0
    if stylesheets.exists():
        for css_file in sorted(stylesheets.glob("*.css")):
            try:
                text = css_file.read_text(encoding="utf-8", errors="ignore")
                parts.append(f"/* === linked: {css_file.name} === */\n{text}\n")
                files += 1
            except Exception:
                continue
    return "\n".join(parts), files


def _strip_angular(css: str, stats: CssExtractStats) -> str:
    # Drop attribute selectors that target Angular's view-encapsulation
    # attributes — they contribute no styling info in a static rebuild.
    cleaned = ANGULAR_ATTR_SELECTOR_RE.sub("", css)

    # Drop rules whose entire selector list is just an Angular custom element.
    # We use a simple line-by-line pass to avoid pulling in a real CSS parser.
    out_lines: list[str] = []
    depth = 0
    buf: list[str] = []
    selector = ""
    for raw_line in cleaned.splitlines(keepends=True):
        line = raw_line
        # Naive selector capture: bytes before the first "{" on a line outside braces
        if depth == 0 and "{" in line:
            sel_part, _, rest = line.partition("{")
            selector = sel_part.strip()
            # If the entire selector matches Angular tag noise, drop this rule
            if ANGULAR_TAG_RE.fullmatch(selector.split(",")[0].strip()) \
                    or any(selector.startswith(p) for p in NOISE_SELECTOR_PREFIXES):
                # Skip until the matching "}"
                depth = 1
                stats.rules_dropped_angular += 1
                continue
            depth += line.count("{") - line.count("}")
            out_lines.append(line)
            continue
        if depth > 0:
            depth += line.count("{") - line.count("}")
            if depth <= 0:
                depth = 0
            continue
        out_lines.append(line)
    return "".join(out_lines)


def _render_tokens_css(design_tokens: dict) -> str:
    lines = [
        "/* tokens.css — generated by dna-website normalizer */",
        "/* DO NOT EDIT — re-run `python -m scripts.normalize` to regenerate */",
        ":root {",
    ]
    color = design_tokens.get("color") or {}
    brand = color.get("brand") or {}
    for k in ("primary", "secondary"):
        val = (brand.get(k) or {}).get("value") if isinstance(brand.get(k), dict) else None
        if val:
            lines.append(f"  --color-brand-{k}: {val};")
    for k, v in (color.get("neutrals") or {}).items():
        val = (v or {}).get("value") if isinstance(v, dict) else v
        if val:
            lines.append(f"  --color-neutral-{k}: {val};")
    accent = color.get("accent") or {}
    for k in ("success", "warning", "danger", "info"):
        v = accent.get(k)
        val = (v or {}).get("value") if isinstance(v, dict) else None
        if val:
            lines.append(f"  --color-accent-{k}: {val};")

    typo = design_tokens.get("typography") or {}
    families = typo.get("families") or {}
    body = families.get("body") or {}
    heading = families.get("heading") or {}
    if body:
        stack = body.get("stack") if isinstance(body, dict) else None
        if stack:
            lines.append(f"  --font-body: {stack};")
    if heading:
        stack = heading.get("stack") if isinstance(heading, dict) else None
        if stack:
            lines.append(f"  --font-heading: {stack};")

    scale_sizes = (typo.get("scale") or {}).get("sizes") or {}
    for name, size in scale_sizes.items():
        rem = (size or {}).get("rem") if isinstance(size, dict) else None
        if rem is not None:
            lines.append(f"  --font-size-{name}: {rem}rem;")

    spacing = (design_tokens.get("spacing") or {}).get("scale") or {}
    for name, entry in spacing.items():
        rem = (entry or {}).get("rem") if isinstance(entry, dict) else None
        if rem is not None:
            lines.append(f"  --space-{name}: {rem}rem;")

    radii = (design_tokens.get("radius") or {}).get("scale") or {}
    for name, px in radii.items():
        val = "9999px" if px == 9999 else f"{px}px"
        lines.append(f"  --radius-{name}: {val};")

    shadows = (design_tokens.get("shadow") or {}).get("scale") or {}
    for name, val in shadows.items():
        lines.append(f"  --shadow-{name}: {val};")

    motion_dur = (design_tokens.get("motion") or {}).get("duration") or {}
    for name, val in motion_dur.items():
        lines.append(f"  --duration-{name}: {val};")
    motion_eas = (design_tokens.get("motion") or {}).get("easing") or {}
    for name, val in motion_eas.items():
        lines.append(f"  --easing-{name}: {val};")

    bps = (design_tokens.get("breakpoint") or {}).get("scale") or {}
    for name, val in bps.items():
        lines.append(f"  --breakpoint-{name}: {val};")

    lines.append("}")
    return "\n".join(lines) + "\n"


def run(
    capture_dir: Path,
    real_project_dir: Path,
    design_tokens: dict,
) -> CssExtractStats:
    """Produce tokens.css + raw.css and stage placeholder base.css."""
    stats = CssExtractStats()
    css_dir = real_project_dir / "assets" / "css"
    css_dir.mkdir(parents=True, exist_ok=True)
    pages_css_dir = css_dir / "pages"
    pages_css_dir.mkdir(exist_ok=True)

    # tokens.css from design DNA
    (css_dir / "tokens.css").write_text(_render_tokens_css(design_tokens), encoding="utf-8")

    # Reset is supplied by templates/ — orchestrator copies it.

    # raw.css from inline + linked CSS, angular-stripped
    inline_text, inline_count = _gather_from_pages(capture_dir / "raw" / "pages")
    linked_text, file_count = _gather_from_assets(capture_dir / "raw" / "assets")
    raw = inline_text + "\n" + linked_text
    stats.bytes_raw_total = len(raw)
    stats.files_read = file_count
    stats.inline_blocks_read = inline_count

    cleaned = _strip_angular(raw, stats)
    stats.bytes_clean_total = len(cleaned)
    (css_dir / "raw.css").write_text(cleaned, encoding="utf-8")

    # base.css placeholder — orchestrator's AI step replaces this.
    (css_dir / "base.css").write_text(
        "/* base.css — pending AI consolidation. Open issue: still placeholder. */\n",
        encoding="utf-8",
    )

    # components.css placeholder
    (css_dir / "components.css").write_text(
        "/* components.css — pending AI consolidation. */\n",
        encoding="utf-8",
    )

    # Persist stats for the run report
    (real_project_dir / "css_extract.stats.json").write_text(json.dumps({
        "files_read": stats.files_read,
        "inline_blocks_read": stats.inline_blocks_read,
        "bytes_raw_total": stats.bytes_raw_total,
        "bytes_clean_total": stats.bytes_clean_total,
        "rules_dropped_angular": stats.rules_dropped_angular,
    }, indent=2), encoding="utf-8")
    return stats
